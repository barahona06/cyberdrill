/**
 * Full exam: 10 questions with explanations, generated by the CLOUD model
 * (rich Spanish generation lives there), with a closing progress analysis
 * also from the cloud.
 *
 * NO SILENT FALLBACK: if the cloud cannot assemble the exam, this screen
 * shows an error phase with the exact recorded cause (HybridAiClient's
 * exam failure detail: which block failed, the server's exception class
 * and message, or the parse shortfall) plus a retry. The seed bank is
 * offered there as an EXPLICIT choice (button, badged "Local bank") —
 * it is never swapped in silently. The seed bank's silent role survives
 * only where it belongs: the on-device / airplane-mode practice flows.
 */
@Composable
fun ExamScreen(
    l: L,
    viewModel: AppViewModel,
    onBack: () -> Unit,
    onHome: () -> Unit
) {
    var phase by remember { mutableStateOf("intro") } // intro | loading | error | answering | results
    var questions by remember { mutableStateOf<List<QuizQuestion>>(emptyList()) }
    var examSource by remember { mutableStateOf(AiSource.SEED_BANK) }
    var examError by remember { mutableStateOf<String?>(null) }
    var index by remember { mutableIntStateOf(0) }
    val answers = remember { mutableStateListOf<Int>() }
    var selected by remember { mutableStateOf<Int?>(null) }
    var analysis by remember { mutableStateOf<AiResult?>(null) }
    var recorded by remember { mutableStateOf(false) }
    // Loading-screen progress: real (questions ready, fed by fetchExam's
    // per-block callback) plus a staged message that advances while the
    // student waits — a mute spinner made the old wait feel endless.
    var examReady by remember { mutableIntStateOf(0) }
    var examStage by remember { mutableIntStateOf(0) }

    LaunchedEffect(phase) {
        if (phase == "loading") {
            examReady = 0
            examStage = 0
            launch {
                while (true) {
                    delay(6_000)
                    examStage++
                }
            }
            // Two parallel blocks with per-block parse reporting
            // (StudyAi.fetchExam). Null NO LONGER means a silent
            // seed-bank exam: it means the error phase, with the
            // recorded cause shown verbatim.
            val fetched = StudyAi.fetchExam(l.lang) { ready, _ -> examReady = ready }
            if (fetched != null) {
                questions = fetched.first
                examSource = fetched.second
                answers.clear()
                index = 0
                selected = null
                phase = "answering"
            } else {
                examError = HybridAiClient.examFailureDetail.value
                    ?: HybridAiClient.lastError.value
                    ?: "—"
                phase = "error"
            }
        }
        if (phase == "results" && !recorded) {
            recorded = true
            val now = System.currentTimeMillis()
            val perTopic = mutableMapOf<String, Pair<Int, Int>>()
            questions.forEachIndexed { i, q ->
                val right = answers.getOrNull(i) == q.answerIndex
                val cur = perTopic[q.topicId] ?: (0 to 0)
                perTopic[q.topicId] = (cur.first + if (right) 1 else 0) to (cur.second + 1)
            }
            val records = perTopic.map { (topicId, sc) ->
                SessionRecord("exam", topicId, sc.first, sc.second, now)
            }.filter { it.topicId != "exam" }
            if (records.isNotEmpty()) viewModel.recordSessions(records)

            val totalCorrect = questions.indices.count { answers.getOrNull(it) == questions[it].answerIndex }
            val named = perTopic.mapKeys { (id, _) ->
                Topics.all.firstOrNull { t -> t.id == id }?.name(l.lang) ?: (l.modeExam)
            }
            val cloudAnalysis = HybridAiClient.generateCloud(
                StudyAi.analysisPrompt(l.lang, named, totalCorrect, questions.size)
            )
            analysis = cloudAnalysis ?: AiResult(
                StudyAi.localAnalysis(l.lang, named, totalCorrect, questions.size),
                AiSource.SEED_BANK
            )
        }
    }

    Column(
        modifier = Modifier.fillMaxSize().padding(16.dp).verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        TextButton(onClick = onBack) { Text("← ${l.backHome}") }
        Text(
            text = l.fullExam,
            style = MaterialTheme.typography.headlineSmall,
            fontWeight = FontWeight.Bold
        )

        when (phase) {
            "intro" -> {
                Text(text = l.examIntro, style = MaterialTheme.typography.bodyLarge)
                Button(
                    onClick = { phase = "loading" },
                    modifier = Modifier.fillMaxWidth()
                ) { Text(l.startExam) }
            }

            "loading" -> {
                CircularProgressIndicator()
                Text(
                    text = when (examStage) {
                        0 -> l.preparingExam
                        1 -> l.examWritingQuestions
                        2 -> l.examWritingExplanations
                        else -> l.examAlmostThere
                    },
                    style = MaterialTheme.typography.bodyLarge
                )
                if (examReady > 0) {
                    Text(
                        text = l.examQuestionsReady(examReady, StudyAi.EXAM_QUESTION_COUNT),
                        style = MaterialTheme.typography.bodyMedium
                    )
                }
            }

            "error" -> {
                Text(
                    text = l.examCloudErrorTitle,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold
                )
                Text(text = l.examCloudErrorBody, style = MaterialTheme.typography.bodyMedium)
                Card(
                    colors = CardDefaults.cardColors(
                        containerColor = MaterialTheme.colorScheme.surfaceVariant
                    ),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Text(
                        text = examError ?: "—",
                        modifier = Modifier.padding(14.dp),
                        style = MaterialTheme.typography.bodySmall
                    )
                }
                Button(
                    onClick = { phase = "loading" },
                    modifier = Modifier.fillMaxWidth()
                ) { Text(l.examRetry) }
                Button(
                    onClick = {
                        // The seed bank as an EXPLICIT choice: the student
                        // taps for it knowingly and the exam carries the
                        // "Local bank" badge — never a silent substitute.
                        questions = SeedBank.examSet()
                        examSource = AiSource.SEED_BANK
                        answers.clear()
                        index = 0
                        selected = null
                        phase = "answering"
                    },
                    modifier = Modifier.fillMaxWidth()
                ) { Text(l.examUseLocalBank) }
            }

            "answering" -> {
                val q = questions.getOrNull(index)
                if (q != null) {
                    Text(
                        text = "${l.questionOf} ${index + 1} / ${questions.size}",
                        style = MaterialTheme.typography.labelLarge
                    )
                    InferenceBadge(source = examSource, l = l)
                    Text(text = q.question(l.lang), style = MaterialTheme.typography.bodyLarge)
                    q.options(l.lang).forEachIndexed { i, opt ->
                        val bg = if (selected == i) {
                            MaterialTheme.colorScheme.primaryContainer
                        } else {
                            MaterialTheme.colorScheme.surfaceVariant
                        }
                        Card(
                            modifier = Modifier.fillMaxWidth().clickable { selected = i },
                            colors = CardDefaults.cardColors(containerColor = bg)
                        ) {
                            Text(
                                text = "${"ABCD"[i]})  $opt",
                                modifier = Modifier.padding(14.dp),
                                style = MaterialTheme.typography.bodyLarge
                            )
                        }
                    }
                    Button(
                        onClick = {
                            answers.add(selected ?: -1)
                            selected = null
                            if (index + 1 >= questions.size) {
                                phase = "results"
                            } else {
                                index++
                            }
                        },
                        enabled = selected != null,
                        modifier = Modifier.fillMaxWidth()
                    ) { Text(l.nextQuestion) }
                }
            }

            "results" -> {
                val totalCorrect =
                    questions.indices.count { answers.getOrNull(it) == questions[it].answerIndex }
                Text(
                    text = "${l.yourScore}: $totalCorrect / ${questions.size}",
                    style = MaterialTheme.typography.headlineSmall,
                    fontWeight = FontWeight.Bold
                )
                InferenceBadge(source = examSource, l = l)

                val a = analysis
                if (a != null) {
                    Card(
                        colors = CardDefaults.cardColors(
                            containerColor = MaterialTheme.colorScheme.primaryContainer
                        ),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Column(modifier = Modifier.padding(14.dp)) {
                            Text(
                                text = l.analysisTitle,
                                style = MaterialTheme.typography.titleSmall,
                                fontWeight = FontWeight.SemiBold
                            )
                            Spacer(Modifier.height(6.dp))
                            Text(text = a.text, style = MaterialTheme.typography.bodyMedium)
                            Spacer(Modifier.height(8.dp))
                            InferenceBadge(source = a.source, l = l)
                        }
                    }
                }

                Text(
                    text = l.reviewTitle,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold
                )
                questions.forEachIndexed { i, q ->
                    val mine = answers.getOrNull(i)
                    val right = mine == q.answerIndex
                    Card(
                        colors = CardDefaults.cardColors(
                            containerColor = if (right) Color(0xFFEDF5EF) else Color(0xFFF9ECEC)
                        ),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Column(modifier = Modifier.padding(14.dp)) {
                            Text(
                                text = "${i + 1}. ${q.question(l.lang)}",
                                fontWeight = FontWeight.SemiBold
                            )
                            Spacer(Modifier.height(4.dp))
                            Text(
                                text = "${if (l.lang == "en") "Correct answer" else "Respuesta correcta"}: " +
                                    q.options(l.lang)[q.answerIndex]
                            )
                            if (!right && mine != null && mine in q.options(l.lang).indices) {
                                Text(
                                    text = "${if (l.lang == "en") "Your answer" else "Tu respuesta"}: " +
                                        q.options(l.lang)[mine]
                                )
                            }
                            Spacer(Modifier.height(4.dp))
                            Text(text = q.explanation(l.lang), style = MaterialTheme.typography.bodySmall)
                        }
                    }
                }

                Button(onClick = onHome, modifier = Modifier.fillMaxWidth()) { Text(l.backHome) }
            }
        }
    }
}
